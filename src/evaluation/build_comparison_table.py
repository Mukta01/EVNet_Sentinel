"""
Build the leaked-vs-corrected comparison table for issue #54.

Reads the prediction CSVs produced by each model, computes macro-F1 (the
headline metric) alongside accuracy and weighted-F1, and emits a single markdown
table placing our corrected numbers next to the figures the paper reports.

Usage
-----
    python3 src/evaluation/build_comparison_table.py \
        --leakfree-dir predictions/leakfree \
        --leaked-dir   predictions \
        --output       evaluation_results/leakfree/COMPARISON.md
"""

import argparse
import glob
import json
import os

import pandas as pd
from sklearn.metrics import accuracy_score, f1_score

# Reported in Makhmudov et al. (2025), Tables 5-6. Measured on data that retains
# the six absolute capture-timestamp columns -- see issue #47.
PAPER_MULTICLASS = {"accuracy": 0.9840, "weighted_f1": 0.9831}

MODEL_LABELS = {
    "rf": "Random Forest",
    "dt": "Decision Tree",
    "svm": "SVM (SGD, hinge)",
    "logreg": "Logistic Regression",
    "arf_adwin": "ARF + ADWIN (online)",
}


def score(path):
    df = pd.read_csv(path)
    if "y_true" not in df.columns or "y_pred" not in df.columns:
        return None
    yt, yp = df["y_true"].astype(str), df["y_pred"].astype(str)
    return {
        "n": len(df),
        "macro_f1": f1_score(yt, yp, average="macro", zero_division=0),
        "weighted_f1": f1_score(yt, yp, average="weighted", zero_division=0),
        "accuracy": accuracy_score(yt, yp),
    }


def collect(directory):
    results = {}
    for path in sorted(glob.glob(os.path.join(directory, "*.csv"))):
        name = os.path.basename(path)
        key = name.split("_pred")[0].rstrip("_")
        try:
            scored = score(path)
        except Exception:
            continue
        if scored:
            results[key] = scored
    return results


def fmt(value):
    return f"{value:.4f}" if value is not None else "—"


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--leakfree-dir", dest="leakfree_dir", default="predictions/leakfree")
    parser.add_argument("--leaked-dir", dest="leaked_dir", default="predictions")
    parser.add_argument("--output", default="evaluation_results/leakfree/COMPARISON.md")
    args = parser.parse_args()

    leakfree = collect(args.leakfree_dir)
    leaked = collect(args.leaked_dir)

    lines = [
        "# Leaked vs. Corrected Results",
        "",
        "Generated by `src/evaluation/build_comparison_table.py` (issue #54).",
        "",
        "**Macro-F1 is the headline metric.** With `ICMP_Fragmentation` at 28 raw flows and",
        "`Benign` at 82, accuracy tracks the flood classes and hides the reconnaissance",
        "classes almost entirely.",
        "",
        "## Multiclass (15 classes)",
        "",
        "| Model | Macro-F1 | Weighted-F1 | Accuracy | Test rows |",
        "|---|---|---|---|---|",
    ]

    for key in ["rf", "dt", "svm", "logreg", "arf_adwin"]:
        entry = leakfree.get(key)
        if not entry:
            continue
        lines.append(f"| {MODEL_LABELS[key]} | **{fmt(entry['macro_f1'])}** | "
                     f"{fmt(entry['weighted_f1'])} | {fmt(entry['accuracy'])} | {entry['n']:,} |")

    lines += [
        f"| _Makhmudov et al. (2025), reported_ | — | _{PAPER_MULTICLASS['weighted_f1']:.4f}_ | "
        f"_{PAPER_MULTICLASS['accuracy']:.4f}_ | _~1.2M_ |",
        "",
        "> The paper's row is **not** a like-for-like comparison: those figures were measured",
        "> on data retaining the six absolute capture-timestamp columns. On that feature set a",
        "> decision tree using `bidirectional_first_seen_ms` alone reaches 0.9976 (issue #47).",
        "",
    ]

    if leaked:
        lines += [
            "## Effect of removing the leak",
            "",
            "Same models, same splits; the only difference is whether the six absolute",
            "`*_seen_ms` columns are present.",
            "",
            "| Model | Macro-F1 (leaked) | Macro-F1 (corrected) | Delta |",
            "|---|---|---|---|",
        ]
        for key in ["rf", "dt", "svm", "logreg"]:
            before, after = leaked.get(key), leakfree.get(key)
            if not (before and after):
                continue
            delta = after["macro_f1"] - before["macro_f1"]
            lines.append(f"| {MODEL_LABELS[key]} | {fmt(before['macro_f1'])} | "
                         f"{fmt(after['macro_f1'])} | {delta:+.4f} |")
        lines.append("")

    drift = sorted(glob.glob(os.path.join(args.leakfree_dir, "*drift_events*.json"))) \
        + sorted(glob.glob("predictions/*drift_events*.json"))
    if drift:
        lines += ["## Stream ordering (issue #53)", "",
                  "| Run | Order | Instances | Accuracy | Weighted-F1 | Drift events | On a capture boundary |",
                  "|---|---|---|---|---|---|---|"]
        for path in drift:
            with open(path) as handle:
                data = json.load(handle)
            if "events" not in data:
                continue
            events = data["events"]
            named = sum(1 for e in events if e.get("source_file"))
            final = data.get("final_metrics", {})
            lines.append(
                f"| `{os.path.basename(path)}` | {data.get('stream_order', '?')} | "
                f"{data.get('instances', 0):,} | {fmt(final.get('accuracy'))} | "
                f"{fmt(final.get('f1'))} | {len(events)} | {named}/{len(events)} |")
        lines.append("")

    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    with open(args.output, "w") as handle:
        handle.write("\n".join(lines))
    print("\n".join(lines))
    print(f"\n[+] Wrote {args.output}")


if __name__ == "__main__":
    main()
